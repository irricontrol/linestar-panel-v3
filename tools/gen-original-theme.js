const fs = require('fs');
const path = require('path');

const ORIG_DIR = '../../smartconnect-panel-main/css';

function stripComments(s) { return s.replace(/\/\*[\s\S]*?\*\//g, ''); }

function extractRules(css) {
  const rules = [];
  let depth = 0, buf = '', selBuf = '';
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (c === '{') {
      if (depth === 0) { selBuf = buf; buf = ''; }
      depth++;
    } else if (c === '}') {
      depth--;
      if (depth === 0) {
        rules.push([selBuf.trim().replace(/\s+/g, ' '), buf.trim().replace(/\s+/g, ' ')]);
        buf = '';
      }
    } else {
      buf += c;
    }
  }
  return rules;
}

function loadRules(file) { return extractRules(stripComments(fs.readFileSync(file, 'utf8'))); }

function bodyFor(rules, selector) {
  const hit = rules.find(([sel]) => sel === selector);
  if (!hit) throw new Error('Selector not found in original: ' + selector);
  return hit[1];
}

function fmtBody(body) {
  return body.replace(/;\s*/g, ';\n  ').replace(/;\n  $/, ';\n');
}

function block(selector, body) {
  return `:root[data-theme="original"] ${selector} {\n  ${fmtBody(body)}}\n`;
}


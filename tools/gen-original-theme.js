/* NOTE: these icons are all stroke-drawn with fill="none" on the <svg>
   itself (chevron/pencil/calendar/circleMinus/circlePlus), always passed
   color:'#ffffff' (or 'currentColor', which resolves to the same white
   .field-btn text color in the original design) — so the correct revert
   is the literal white, not `unset`. Setting `fill: unset` here was the
   original bug: it makes the browser ignore the element's own
   fill="none" attribute and fall back to CSS's inherited/initial fill,
   which for `fill` is black — turning every "invisible" icon outline
   into a solid black wedge. Leaving `fill` alone entirely (not declared)
   lets the fill="none" attribute do its job undisturbed. */

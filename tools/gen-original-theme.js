// Part 1: reproduce every original rule verbatim, scoped.
// ---------------------------------------------------------------------
const FILES = ['components.css', 'pages.css', 'layout.css'];
let out = `/**
 * Theme: Original — the pre-metallic look (smartconnect-panel-main),
 * reproduced verbatim and scoped under [data-theme="original"] so it can
 * sit alongside the current default ("Metallic") and dark-theme.css
 * without touching either. Generated by gen-original-theme.js — Part 1
 * mechanically reproduces every rule from the untouched original CSS;
 * Part 2 explicitly neutralizes the metallic-only additions (glass
 * gloss overlays, chrome text-clip, per-button svg recoloring) that
 * don't exist in the original at all, so they don't leak through here.
 * Do not hand-edit — regenerate from gen-original-theme.js instead.
 * Toggle: Config -> System -> Theme.
 */

`;

const origRulesByFile = {};
for (const file of FILES) {
  const origPath = path.join(ORIG_DIR, file);
  if (!fs.existsSync(origPath)) continue;
  const rules = loadRules(origPath);
  origRulesByFile[file] = rules;
  out += `/* ==== Part 1: reproduced from ${file} ==== */\n`;
  for (const [sel, body] of rules) {
    if (!body) continue;
    for (const s of sel.split(',').map(x => x.trim()).filter(Boolean)) {
      out += block(s, body);
    }
  }
  out += '\n';
}

